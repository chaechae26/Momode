// AI 고민 상담 API
app.post('/api/chat', async (req, res) => {
  try {
    const { mbti, message, history = [] } = req.body;

    // 입력값 확인
    if (!validMBTI.includes(mbti)) {
      return res.status(400).json({
        error: '올바른 MBTI를 선택해 주세요.'
      });
    }

    if (typeof message !== 'string' || !message.trim()) {
      return res.status(400).json({
        error: '고민 내용을 입력해 주세요.'
      });
    }

    if (message.length > 2000) {
      return res.status(400).json({
        error: '고민은 2,000자 이내로 입력해 주세요.'
      });
    }

    // 대화 기록 정리
    const safeHistory = Array.isArray(history)
      ? history
          .filter(item =>
            item &&
            ['user', 'assistant'].includes(item.role) &&
            typeof item.content === 'string'
          )
          .slice(-10)
          .map(item => ({
            role: item.role,
            content: item.content.slice(0, 2000)
          }))
      : [];

    // API 키 확인 및 OpenAI 연결
    if (!process.env.OPENAI_API_KEY) {
      return res.status(500).json({
        error: 'OpenAI API 키가 설정되지 않았습니다.'
      });
    }

    const openai = new OpenAI({
      apiKey: process.env.OPENAI_API_KEY
    });

    // MBTI에 따른 맞춤형 상담 지침
    const instructions = `
당신은 맘모드(MOMODE)라는 AI 고민 상담 챗봇입니다.

사용자가 선택한 MBTI는 ${mbti}입니다.

[유형별 맞춤 상담 지침]
${mbtiGuides[mbti]}

[공통 상담 원칙]
1. 사용자의 고민을 먼저 충분히 경청합니다.
2. MBTI에 맞는 관점과 조언 방식을 적용합니다.
3. 단순히 말투만 바꾸지 말고 문제를 바라보는
   관점과 해결책의 구성도 유형에 맞게 조절합니다.
4. 사용자가 원하는 경우 현실적인 해결 방법을 제안합니다.
5. 무조건적인 긍정이나 형식적인 위로는 피합니다.
6. 자연스럽고 따뜻한 한국어를 사용합니다.
7. 사용자의 실제 상황과 감정을 MBTI보다 우선합니다.
8. 필요한 경우 추가 질문을 통해 고민을 구체적으로 이해합니다.

[중요한 주의사항]
MBTI는 개인의 성격을 완벽하게 설명하지 않습니다.
특정 유형의 사람들이 모두 동일하게 행동한다고
단정하거나 일반화하지 마세요.

사용자의 성향은 상담의 참고 자료로만 활용하고,
개인의 실제 감정과 상황을 존중하세요.

전문적인 정신건강 진단을 대신하지 않으며,
자해 등 긴급한 위험이 드러나면 안전 확보와
전문적인 도움을 우선 안내하세요.

사용자가 자신의 이야기를 편안하게 나눌 수 있도록
진정성 있고 이해하기 쉬운 답변을 제공합니다.
`;


    // OpenAI API에 질문 전달
    const response = await openai.responses.create({
      model: process.env.OPENAI_MODEL || 'gpt-6-luna',
      instructions: instructions,
      input: [
        ...safeHistory,
        {
          role: 'user',
          content: message
        }
      ],
      max_output_tokens: 500
    });

    // AI 답변 반환
    res.json({
      reply: response.output_text
    });

  } catch (error) {
    console.error('AI 응답 오류:', error);

    res.status(500).json({
      error: '답변을 생성하지 못했습니다. 잠시 후 다시 시도해 주세요.'
    });
  }
});

// 서버 실행
app.listen(PORT, '0.0.0.0', () => {
  console.log(`맘모드 서버 실행 중: http://localhost:${PORT}`);
});
